const norm = s => String(s || '').replace(/\s+/g, '').toLowerCase();

/** 按名称/别名查找食物（优先更长名称，避免「酸奶」截胡「希腊酸奶」）。
 *  custom: 用户自定义食物库 { 名称: {k,p,c,f,g,u} }，优先级最高 */
export function findFood(text, custom) {
  if (!text) return null;
  const q = norm(text);
  if (!q) return null;
  // 用户自定义库：完全匹配 → 包含匹配
  if (custom) {
    for (const name of Object.keys(custom)) {
      if (norm(name) === q) return customToFood(name, custom[name]);
    }
    const ck = Object.keys(custom).sort((a, b) => b.length - a.length)
      .find(name => q.includes(norm(name)) || norm(name).includes(q));
    if (ck) return customToFood(ck, custom[ck]);
  }
  const sorted = FOODS.slice().sort((a, b) => b.n.length - a.n.length);
  let hit = sorted.find(f => norm(f.n) === q || (f.a || []).some(al => norm(al) === q));
  if (hit) return hit;
  // 包含匹配：名称或别名是文本的一部分（取最长的）
  hit = sorted.find(f => q.includes(norm(f.n)) || (f.a || []).some(al => q.includes(norm(al))));
  return hit || null;
}

function customToFood(name, c) {
  return { n: name, a: [], u: c.u || '份', g: c.g || 100, k: c.k, p: c.p, c: c.c, f: c.f, t: ['custom'] };
}
